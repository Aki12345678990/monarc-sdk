// Generates src/lib/report-types.ts from the engine's Report JSON Schema
// (`python -m analyzer_core schema`) plus the engine's ErrorCode values.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const webDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const python =
  process.platform === "win32"
    ? join(webDir, "..", ".venv", "Scripts", "python.exe")
    : join(webDir, "..", ".venv", "bin", "python");

function run(args) {
  const result = spawnSync(python, args, { cwd: webDir, encoding: "utf-8" });
  if (result.status !== 0) {
    process.stderr.write(result.stderr ?? "");
    throw new Error(`${python} ${args.join(" ")} exited with ${result.status}`);
  }
  return result.stdout;
}

const schema = JSON.parse(run(["-m", "analyzer_core", "schema"]));
const errorCodes = JSON.parse(
  run([
    "-c",
    "import json; from analyzer_core.errors import ErrorCode; print(json.dumps([c.value for c in ErrorCode]))",
  ]),
);

const types = await compile(schema, "Report", {
  additionalProperties: false,
  bannerComment:
    "/* Generated by `npm run gen:types` from `python -m analyzer_core schema`. Do not edit. */",
});

const codes = [
  "",
  "/** Values of analyzer_core.errors.ErrorCode. */",
  `export const ENGINE_ERROR_CODES = ${JSON.stringify(errorCodes)} as const;`,
  "export type EngineErrorCode = (typeof ENGINE_ERROR_CODES)[number];",
  "",
].join("\n");

const target = join(webDir, "src", "lib", "report-types.ts");
writeFileSync(target, types + codes, "utf-8");
console.log(`wrote ${target} (${errorCodes.length} error codes)`);
